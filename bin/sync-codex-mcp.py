#!/usr/bin/env python3
"""Mirror Claude's directory-scoped MCP registrations into local Codex config."""

import json
import os
import subprocess
import tomllib
from pathlib import Path


HOME = Path.home()
WORKSPACE = HOME / "workspace"
MARKER = "# Generated by ~/.claude/bin/sync-codex-mcp.py; edit Claude MCP sources."


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def render(servers):
    lines = [MARKER, ""]
    for name, server in sorted(servers.items()):
        section = f"mcp_servers.{quoted(name)}"
        lines.append(f"[{section}]")
        lines.append("enabled = true")
        if "url" in server:
            lines.append(f"url = {quoted(server['url'])}")
        else:
            lines.append(f"command = {quoted(server['command'])}")
            lines.append(f"args = {quoted(server.get('args', []))}")
        if server.get("env"):
            entries = ", ".join(
                f"{quoted(key)} = {quoted(value)}"
                for key, value in sorted(server["env"].items())
            )
            lines.append(f"env = {{ {entries} }}")
        if server.get("oauth"):
            oauth = server["oauth"]
            lines.append("")
            lines.append(f"[{section}.oauth]")
            if "clientId" in oauth:
                lines.append(f"client_id = {quoted(oauth['clientId'])}")
            if "callbackPort" in oauth:
                lines.append(f"callback_port = {oauth['callbackPort']}")
        lines.append("")
    result = "\n".join(lines)
    tomllib.loads(result)
    return result


def exclude_generated(target):
    found = subprocess.run(
        ["git", "-C", str(target), "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        check=False,
    )
    if found.returncode:
        return
    root = Path(found.stdout.strip())
    relative = (target / ".codex/config.toml").relative_to(root)
    exclude_path = subprocess.check_output(
        ["git", "-C", str(target), "rev-parse", "--path-format=absolute", "--git-path", "info/exclude"],
        text=True,
    ).strip()
    exclude = Path(exclude_path)
    pattern = "/" + relative.as_posix()
    existing = exclude.read_text() if exclude.exists() else ""
    if pattern not in existing.splitlines():
        with exclude.open("a") as file:
            if existing and not existing.endswith("\n"):
                file.write("\n")
            file.write(pattern + "\n")


def main():
    claude = json.loads((HOME / ".claude.json").read_text())
    targets = {}
    for dirname, project in claude.get("projects", {}).items():
        path = Path(dirname)
        if not path.is_relative_to(WORKSPACE) or not path.is_dir():
            continue
        if any(part in {".worktrees", "worktrees", "_archive"} for part in path.parts):
            continue
        servers = project.get("mcpServers", {}).copy()
        for source in (path / ".claude/settings.json", path / ".mcp.json"):
            if source.exists():
                servers.update(json.loads(source.read_text()).get("mcpServers", {}))
        if servers:
            targets[path] = servers

    for root, dirs, _ in os.walk(WORKSPACE):
        path = Path(root)
        depth = len(path.relative_to(WORKSPACE).parts)
        dirs[:] = [] if depth >= 3 else [
            item for item in dirs
            if item not in {".git", ".claude", ".codex", ".worktrees", "worktrees", "_archive", "node_modules", ".build", ".venv", ".local"}
        ]
        for source in (path / ".claude/settings.json", path / ".mcp.json"):
            if source.exists():
                servers = json.loads(source.read_text()).get("mcpServers", {})
                if servers:
                    targets.setdefault(path, {}).update(servers)

    for target, servers in sorted(targets.items()):
        config = target / ".codex/config.toml"
        content = render(servers)
        if config.exists():
            previous = config.read_text()
            if not previous.startswith(MARKER):
                raise RuntimeError(f"Refusing to replace unmanaged config: {config}")
            if previous == content:
                print(f"unchanged {config}")
                continue
        config.parent.mkdir(exist_ok=True)
        exclude_generated(target)
        temporary = config.with_suffix(".toml.tmp")
        with os.fdopen(os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as file:
            file.write(content)
        temporary.replace(config)
        config.chmod(0o600)
        print(f"updated {config}")


if __name__ == "__main__":
    main()
